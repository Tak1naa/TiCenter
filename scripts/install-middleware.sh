echo "  sudo systemctl start rabbitmq-server"
echo "  sudo rabbitmq-plugins enable rabbitmq_management"
echo ""

echo "### Milvus 2.4 (Vector Database)"
echo "Recommended: Docker standalone"
echo "  wget https://github.com/milvus-io/milvus/releases/download/v2.4.0/milvus-standalone-docker-compose.yml -O docker-compose.yml"
echo "  docker-compose up -d"
echo ""
echo "Or without Docker (binary install):"
echo "  https://milvus.io/docs/install_standalone-docker.md"
echo ""

echo "### MinIO (Object Storage for OCR cache images)"
echo "  wget https://dl.min.io/server/minio/release/linux-amd64/minio"
echo "  chmod +x minio"
echo "  MINIO_ROOT_USER=admin MINIO_ROOT_PASSWORD=admin123 ./minio server /data/minio"
echo ""

