echo "  Fedora: sudo dnf install mysql-server mysql"
echo "  Ubuntu: sudo apt install mysql-server"
echo ""
echo "After install:"
echo "  sudo systemctl start mysqld"
echo "  sudo mysql_secure_installation"
echo "  mysql -u root -p < scripts/init-db.sql"
echo ""

echo "### Redis 7"
echo "  Fedora: sudo dnf install redis"
echo "  Ubuntu: sudo apt install redis-server"
echo ""
echo "After install:"
echo "  sudo systemctl start redis"
echo ""

echo "### RabbitMQ 3.13"
echo "  Fedora: sudo dnf install rabbitmq-server"
echo "  Ubuntu: sudo apt install rabbitmq-server"
echo ""
